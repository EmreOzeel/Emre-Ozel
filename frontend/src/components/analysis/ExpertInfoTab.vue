<script setup lang="ts">
import { computed } from 'vue'
import type { CaptureAssessment, ExpertInfo } from '@/types/analysis'

const props = defineProps<{
  assessment: CaptureAssessment | null
  expertInfo: ExpertInfo[]
}>()

const qualityType = computed(() => {
  const q = props.assessment?.quality
  if (q === 'good') return 'success'
  if (q === 'partial') return 'warning'
  if (q === 'poor') return 'danger'
  return 'info'
})

function expertTagType(sev: string): string {
  if (sev === 'error') return 'danger'
  if (sev === 'warn') return 'warning'
  if (sev === 'note') return 'info'
  return ''
}
</script>

