      <template #header><span class="card-title">Analysis Limitations</span></template>
      <ul class="disclaimer-list">
        <li>Protocol identification is based on port numbers and application-layer markers. Without application data (e.g., TLS-encrypted sessions), protocol labels are <strong>inferred</strong>, not confirmed.</li>
        <li>Host role classification (client/server/gateway) is derived from connection patterns and is <strong>not authoritative</strong>.</li>
        <li>Security findings are generated by rule-based heuristics. They indicate suspicion, not forensic certainty. Findings must be validated by an analyst.</li>
